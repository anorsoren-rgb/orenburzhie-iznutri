// ---------- 4.6 «Спроси про Орск» (RAG) ----------
export const CHAT_SYSTEM = `${SYSTEM_BASE}

Ты отвечаешь на вопросы о Орске и Оренбургской области.
Тебе передают материалы сайта (если они есть) и вопрос пользователя.

ПРАВИЛА:
1. Если в материалах есть информация — отвечай по ним, свободно и живо.
2. НЕ добавляй фразу «в моей базе нет ответа», если ответ дан в материалах.
3. Только если материалы ПУСТЫЕ или НЕ относятся к вопросу — скажи:
   «Хороший вопрос! В материалах сайта пока нет ответа, но я его записал — 
   мы постараемся добавить информацию.»
4. Не выдумывай места, даты, события, которых нет в материалах.
5. Отвечай кратко (3–5 предложений), дружелюбно, без канцелярита.`;

export function chatUserPrompt(question: string, context: string[]) {
  const ctx = context.length
    ? `Материалы сайта:\n\n${context.map((c, i) => `[${i + 1}]\n${c}`).join("\n\n")}`
    : "Материалов по теме не найдено.";

  return `${ctx}\n\nВопрос пользователя: ${question}`;
}
